export function planFor(text) {
  const tags = tagsOf(text);
  const pack = packOf[text] || 'custom';
  const has = t => tags.includes(t);

  let hours = HOURS[text];
  if (hours == null) {
    if (pack === 'nature') hours = 4;
    else if (has('water')) hours = 3;
    else if (pack === 'food') hours = 1.5;
    else if (pack === 'night') hours = 3;
    else if (has('sport') || has('games')) hours = 2;
    else if (has('culture')) hours = 2.5;
    else hours = 2.5;
  }

  let start = START[text];
  if (!start) {
    if (has('night') || has('dark')) start = '20:30';
    else if (pack === 'nature' || has('water') || has('walk') && has('sport')) start = '09:00';
    else if (hours >= 4) start = '10:00'; // a long day thing (zoo, amusement park) can't start at five
    else if (pack === 'food') start = '19:30';
    else start = '17:00';
  }

  const bring = [];
  if (has('water')) bring.push('🩱 בגד ים', '🧴 קרם הגנה', '🏖️ מגבת');
  if (pack === 'nature' || has('walk')) bring.push('👟 נעליים נוחות', '💧 בקבוק מים');
  if (pack === 'nature' && !has('night')) bring.push('🧢 כובע');
  if (has('night') || has('dark')) bring.push('🔦 פנס', '🧥 ג\'קט');
  if (has('sport')) bring.push('👕 בגדי ספורט');
  if (has('height') || has('extreme')) bring.push('👟 נעליים סגורות');
  if (has('food') && !NO_TRIP.has(text)) bring.push('💳 כסף לאוכל');
  if (has('money')) bring.push('💳 כסף או כרטיס');
  if (has('creative')) bring.push('📸 טלפון טעון לתמונות');
  bring.push('🔋 מטען נייד');

  return {
    hours, start,
    bring: [...new Set(bring)].slice(0, 7),
    trip: !NO_TRIP.has(text),
    search: SEARCH[text] ?? text,
  };
}

// "HH:MM" plus minutes, wrapping past midnight.
export function addMin(hhmm, min) {
  const [h, m] = hhmm.split(':').map(Number);
  const t = (((h * 60 + m + Math.round(min)) % 1440) + 1440) % 1440;
  return `${String(Math.floor(t / 60)).padStart(2, '0')}:${String(t % 60).padStart(2, '0')}`;
}
